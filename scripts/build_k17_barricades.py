#!/usr/bin/env python3
"""Generate physical prop models and their runtime catalog from one JSON source."""
import argparse
import json
from pathlib import Path
import xml.etree.ElementTree as ET
from build_k17 import Map

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT/'src/maps/k17/barricades/Stockroom.rbxmx'
CONFIG = TARGET.with_name('Config.luau')
CATALOG = json.loads(TARGET.with_name('catalog.json').read_text())


def lua(value):
    if isinstance(value,dict):return 'table.freeze({'+','.join(k+'='+lua(v) for k,v in value.items())+'})'
    if isinstance(value,bool):return str(value).lower()
    return json.dumps(value,ensure_ascii=False)


def build():
    m=Map();m.root.find('Properties/string[@name="Name"]').text='ZO_Barricades'
    # Hull dimensions and homes are checked against the runtime catalog in Studio.
    for name,prop in CATALOG['Props'].items():
        kind,x,y,z=(prop[k] for k in ('Kind','X','Y','Z'))
        w,h,d=(CATALOG['Kinds'][kind][k] for k in ('Width','Height','Depth'))
        hull=m.box(name,'Hull',(x-w/2,x+w/2,z-d/2,z+d/2),y,y+h,alpha=1,shadow=False)
        hull.set('referent',name+'Hull')
        m.prop(m.group(name).find('Properties'),'Ref','PrimaryPart',name+'Hull')
        def box(label,rect,low,high,color='steel',material='Metal'):
            return m.box(name,label,(x+rect[0],x+rect[1],z+rect[2],z+rect[3]),y+low,y+high,color,material,physical=False)
        if kind=='Cabinet':
            box('SteelCarcass',(-2.35,2.35,-1,1),.15,6.2,'olive')
            for a,b in [(-2.2,-.07),(.07,2.2)]:
                box('DoorPanel',(a,b,-1.09,-1.01),.4,5.95,'steel')
                for height in (4.85,5.1,5.35): box('VentSlot',(a+.28,b-.28,-1.1,-1.09),height,height+.07,'dark')
            for a in (-.28,.18):box('DoorLatch',(a,a+.1,-1.1,-1.02),2.8,3.4,'yellow')
            box('KickPlate',(-2.3,2.3,-1.08,-1.01),.15,.4,'rust')
            for a in (-2.2,1.9):box('Foot',(a,a+.3,-.9,.9),0,.15,'dark')
        elif kind=='Table':
            # An overturned workshop table: timber face toward -Z, folded steel legs behind.
            box('TimberTop',(-3,3,-1.2,-.88),0,3.6,'wood','WoodPlanks')
            for height in (.16,3.14):
                box('EdgeFrame',(-2.95,2.95,-.88,-.68),height,height+.3,'steel')
                for a in (-2.8,2.5):box('Leg',(a,a+.3,-.68,1.2),height,height+.3,'steel')
            box('CrossBrace',(-2.8,2.8,.9,1.15),.26,.46,'rust')
        else:
            box('CrateBody',(-1.7,1.7,-1.7,1.7),.2,3.4,'wood','WoodPlanks')
            for a in (-1.75,1.5):
                box('SteelBand',(a,a+.25,-1.75,1.75),.2,3.5,'steel')
            for height in (.35,2.9):box('FaceBrace',(-1.7,1.7,-1.75,-1.7),height,height+.18,'rust')
            for a in (-1.6,1.1):box('PalletRunner',(a,a+.5,-1.7,1.7),0,.2,'dark','Wood')
    ET.indent(m.xml,space='  ')
    return ET.tostring(m.xml,encoding='unicode')+'\n'


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    outputs={TARGET:build(),CONFIG:'--!strict\n-- Generated by scripts/build_k17_barricades.py; edit catalog.json.\nreturn '+lua(CATALOG)+'\n'}
    for path,output in outputs.items():
        if args.check:assert path.read_text()==output,str(path)+' is stale; run scripts/build_k17_barricades.py'
        else:path.write_text(output)
    print(f'PASS barricade authoring: {len(CATALOG["Props"])} props across five refuges, one catalog')
